"""Build frontend/js/route-meta.js (route name, mode, length, ferry wharves) from Metlink's static GTFS.

Usage: uv run scripts/build_route_meta.py [path/to/full.zip]
Re-run when the timetable changes (see feed_end_date in feed_info.txt).
"""
import csv, io, json, statistics, sys, urllib.request, zipfile
from collections import defaultdict
from pathlib import Path

URL = "https://static.opendata.metlink.org.nz/v1/gtfs/full.zip"
OUT = Path(__file__).resolve().parent.parent / "frontend/js/route-meta.js"

src = sys.argv[1] if len(sys.argv) > 1 else io.BytesIO(urllib.request.urlopen(URL, timeout=120).read())
z = zipfile.ZipFile(src)
rows = lambda name: csv.DictReader(io.TextIOWrapper(z.open(name), encoding="utf-8-sig"))

shape_m = defaultdict(float)
for r in rows("shapes.txt"):
    shape_m[r["shape_id"]] = max(shape_m[r["shape_id"]], float(r["shape_dist_traveled"] or 0))
route_m = defaultdict(list)
trip_route = {}
for r in rows("trips.txt"):
    trip_route[r["trip_id"]] = r["route_id"]
    if r["shape_id"] in shape_m:
        route_m[r["route_id"]].append(shape_m[r["shape_id"]])

# Ferries report positions without a route or trip, so their stops (wharves) are kept to detect docking
ferry_routes = {r["route_id"] for r in rows("routes.txt") if r["route_type"] == "4"}
route_stops = defaultdict(set)
for r in rows("stop_times.txt"):
    route = trip_route.get(r["trip_id"])
    if route in ferry_routes:
        route_stops[route].add(r["stop_id"])
stops = {r["stop_id"]: r for r in rows("stops.txt")}

meta = {}
for r in rows("routes.txt"):
    m = route_m.get(r["route_id"])
    meta[r["route_id"]] = {"name": r["route_short_name"], "type": int(r["route_type"]),
                           "km": round(statistics.median(m) / 1000, 1) if m else None}
    if r["route_id"] in route_stops:
        meta[r["route_id"]]["stops"] = sorted([round(float(stops[i]["stop_lat"]), 6), round(float(stops[i]["stop_lon"]), 6), stops[i]["stop_name"]]
                                              for i in route_stops[r["route_id"]])

names = [m["name"] for m in meta.values()]
assert len(names) == len(set(names)), "route_short_name is not unique; audio keys on it"
feed = next(rows("feed_info.txt"))
body = ",\n".join(f'  "{k}": {json.dumps(v)}' for k, v in sorted(meta.items(), key=lambda kv: kv[1]["name"]))
OUT.write_text(f"// Generated by scripts/build_route_meta.py from GTFS {feed['feed_start_date']}-{feed['feed_end_date']}. Do not edit.\n"
               f"// route_id -> short name, GTFS route_type (2 rail, 3 bus, 4 ferry, 5 cable car, 712 school), median trip length km,\n"
               f"// and for ferries their stops [lat, lon, name]\n"
               f"window.ROUTE_META = {{\n{body}\n}};\n")
print(f"wrote {len(meta)} routes to {OUT}")
